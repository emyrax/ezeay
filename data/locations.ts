export function getStatesForCountry(countryName: string): string[] {
  if (!countryName) return [];
  const normalized = countryName.trim();
  const direct = AFRICAN_STATES_DATA[normalized];
  if (direct) return direct;

  const key = Object.keys(AFRICAN_STATES_DATA).find(
    (k) => k.toLowerCase() === normalized.toLowerCase(),
  );
  return key ? AFRICAN_STATES_DATA[key] : [];
}

export function getPopularStatesForCountry(countryName: string): string[] {
  if (!countryName) return [];
  const normalized = countryName.trim();
  const direct = POPULAR_STATES_DATA[normalized];
  if (direct) return direct;

  const key = Object.keys(POPULAR_STATES_DATA).find(
    (k) => k.toLowerCase() === normalized.toLowerCase(),
  );
  if (key) return POPULAR_STATES_DATA[key];

  const all = getStatesForCountry(countryName);
  return all.slice(0, 6);
}

